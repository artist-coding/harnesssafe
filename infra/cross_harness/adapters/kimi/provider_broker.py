    @staticmethod
    def _read_credential(descriptor: int) -> bytearray:
        value = bytearray()
        while len(value) <= 16 * 1024:
            chunk = os.read(descriptor, min(4096, 16 * 1024 + 1 - len(value)))
            if not chunk:
                break
            value.extend(chunk)
        if not value or len(value) > 16 * 1024 or any(byte in value for byte in b"\r\n\0"):
            _wipe(value)
            raise KimiProviderBrokerError("credential descriptor content is invalid")
        return value

