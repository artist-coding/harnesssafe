def _credential_descriptor_shape(descriptor: int) -> str:
    if not isinstance(descriptor, int) or isinstance(descriptor, bool) or descriptor < 3:
        raise KimiProviderBrokerError("credential_fd must be an open descriptor >= 3")
    try:
        metadata = os.fstat(descriptor)
        flags = fcntl.fcntl(descriptor, fcntl.F_GETFD)
    except OSError as exc:
        raise KimiProviderBrokerError("credential_fd is unavailable") from exc
    if flags & fcntl.FD_CLOEXEC == 0:
        raise KimiProviderBrokerError("credential_fd must be close-on-exec by default")
    if stat.S_ISFIFO(metadata.st_mode):
        return "pipe_fd"
    if stat.S_ISREG(metadata.st_mode):
        try:
            target = os.readlink(f"/proc/self/fd/{descriptor}")
            seals = fcntl.fcntl(descriptor, fcntl.F_GET_SEALS)
        except OSError as exc:
            raise KimiProviderBrokerError(
                "regular credential_fd must be an observable sealed memfd"
            ) from exc
        required = (
            fcntl.F_SEAL_SEAL
            | fcntl.F_SEAL_SHRINK
            | fcntl.F_SEAL_GROW
            | fcntl.F_SEAL_WRITE
        )
        if "memfd:" not in target or seals & required != required:
            raise KimiProviderBrokerError(
                "regular credential_fd must be a sealed memfd"
            )
        return "sealed_memfd"
    raise KimiProviderBrokerError("credential_fd must be a pipe or sealed memfd")


def _recv_packet(connection: socket.socket) -> tuple[Mapping[str, Any], list[int]]:
    flags = getattr(socket, "MSG_CMSG_CLOEXEC", 0)
    payload, ancillary, message_flags, _ = connection.recvmsg(
        _MAX_CONTROL_PACKET,
        socket.CMSG_SPACE(array("i", [0]).itemsize),
        flags,
    )
    if not payload or message_flags & (socket.MSG_TRUNC | socket.MSG_CTRUNC):
        raise KimiProviderBrokerError("broker control packet is absent or truncated")
    try:
        document = json.loads(payload.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise KimiProviderBrokerError("broker control packet is malformed") from exc
    if not isinstance(document, Mapping):
        raise KimiProviderBrokerError("broker control packet must be an object")
    descriptors: list[int] = []
    for level, kind, data in ancillary:
        if level == socket.SOL_SOCKET and kind == socket.SCM_RIGHTS:
            values = array("i")
            values.frombytes(data[: len(data) - (len(data) % values.itemsize)])
            descriptors.extend(values)
    return document, descriptors


def _send_packet(
    connection: socket.socket,
    document: Mapping[str, Any],
    *,
    descriptor: int | None = None,
) -> None:
    payload = json.dumps(
        document, sort_keys=True, separators=(",", ":"), ensure_ascii=False
    ).encode("utf-8")
    ancillary: list[tuple[int, int, bytes]] = []
    if descriptor is not None:
        ancillary.append((socket.SOL_SOCKET, socket.SCM_RIGHTS, array("i", [descriptor])))
    sent = connection.sendmsg([payload], ancillary)
    if sent != len(payload):
        raise KimiProviderBrokerError("broker control packet was partially sent")


class RunScopedProviderBroker:
    """Parent-side handle for one independently owned broker subprocess."""

    def __init__(
        self,
        *,
        ownership_root: Path | str,
        run_id: str,
        case_id: str,
        trial_id: str,
        upstream_url: str,
        credential_fd: int,
        allowed_https_hosts: Sequence[str] = (),
        python_executable: Path | str | None = None,
        startup_timeout: float = 15.0,
        upstream_timeout: float = 300.0,
    ) -> None:
        self.run_id = _require_run_id(run_id)
        self.case_id = _require_id(case_id, "case_id")
        self.trial_id = _require_id(trial_id, "trial_id")
        self.endpoint = UpstreamEndpoint.parse(
            upstream_url, allowed_https_hosts=allowed_https_hosts
        )
        self.credential_transport = _credential_descriptor_shape(credential_fd)
        ownership = Path(ownership_root).absolute()
        if not ownership.is_dir() or ownership.is_symlink():
            raise KimiProviderBrokerError("ownership_root must be an existing directory")
        self.ownership_root = ownership.resolve(strict=True)
        if self.ownership_root != ownership or self.ownership_root.stat().st_mode & 0o077:
            raise KimiProviderBrokerError("ownership_root must be private and symlink-free")
        if (
            "kimi" not in self.ownership_root.as_posix().casefold()
            or self.run_id not in self.ownership_root.as_posix()
            or any(
                part.casefold() in {".claude", ".codex", ".kimi-code"}
                for part in self.ownership_root.parts
            )
        ):
            raise KimiProviderBrokerError("ownership_root lacks Kimi/run ownership")
        broker_name = broker_root_name(self.run_id, self.case_id, self.trial_id)
        self.root = self.ownership_root / broker_name
        _reject_symlink_chain(self.root, stop=self.ownership_root, label="broker root")
        if self.root.exists() or self.root.is_symlink():
            raise KimiProviderBrokerError("broker root already exists")
        self.socket_path = self.root / BROKER_SOCKET_BASENAME
        # Linux pathname AF_UNIX addresses have a 108-byte sockaddr field
        # including the terminating NUL.  Formal runs must therefore choose a
        # deliberately short external result root; silently relocating this
        # socket would break run ownership.
        socket_path_length = len(os.fsencode(self.socket_path))
        if socket_path_length >= LINUX_AF_UNIX_PATH_LIMIT:
            raise KimiProviderBrokerError(
                f"run-owned broker socket path is {socket_path_length} bytes and "
                "exceeds the Linux AF_UNIX pathname limit (107 bytes); choose "
                "a shorter --result-root or --run-id"
            )
        self.root.mkdir(mode=0o700)
        self.attestation_path = self.root / f"attestation-kimi-{self.run_id}.json"
        self.audit_attestation_path = (
            self.root / f"audit-attestation-kimi-{self.run_id}.json"
        )
        self.audit_log_path = self.root / f"audit-kimi-{self.run_id}.jsonl"
        executable = Path(
            python_executable or getattr(sys, "_base_executable", sys.executable)
        ).resolve(strict=True)
        implementation = Path(__file__).resolve(strict=True)
        if not executable.is_file() or not os.access(executable, os.X_OK):
            raise KimiProviderBrokerError("broker Python executable is unavailable")
        self.process_executable_path = executable
        self.process_executable_sha256 = _file_sha256(executable)
        self.implementation_path = implementation
        self.implementation_sha256 = _file_sha256(implementation)
        parent_control, child_control = socket.socketpair(
            socket.AF_UNIX, socket.SOCK_SEQPACKET | socket.SOCK_CLOEXEC
        )
        parent_control.settimeout(startup_timeout)
        command = [
            str(executable),
            str(implementation),
            "--worker",
            "--control-fd",
            str(child_control.fileno()),
            "--credential-fd",
            str(credential_fd),
            "--credential-transport",
            self.credential_transport,
            "--root",
            str(self.root),
            "--run-id",
            self.run_id,
            "--case-id",
            self.case_id,
            "--trial-id",
            self.trial_id,
            "--upstream-scheme",
            self.endpoint.scheme,
            "--upstream-host",
            self.endpoint.host,
            "--upstream-port",
            str(self.endpoint.port),
            "--upstream-path-prefix",
            self.endpoint.path_prefix,
            "--upstream-timeout",
            str(float(upstream_timeout)),
        ]
        environment = {
            "PATH": "/usr/local/bin:/usr/bin:/bin",
            "LANG": "C.UTF-8",
            "LC_ALL": "C.UTF-8",
            "PYTHONDONTWRITEBYTECODE": "1",
            "PYTHONNOUSERSITE": "1",
            "PYTHONSAFEPATH": "1",
        }
        self._control = parent_control
        self._rpc_lock = threading.Lock()
        self._closed = False
        self._instruction_observers: dict[
            int, tuple[Path, str, tuple[str, ...]]
        ] = {}
        self._process: subprocess.Popen[bytes] | None = None
        try:
            self._process = subprocess.Popen(
                command,
                stdin=subprocess.DEVNULL,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.PIPE,
                cwd=self.root,
                env=environment,
                close_fds=True,
                pass_fds=(child_control.fileno(), credential_fd),
                start_new_session=True,
            )
            self.pid = self._process.pid
            self.start_time = _process_start_time(self.pid)
            child_control.close()
            try:
                ready, descriptors = _recv_packet(self._control)
            except KimiProviderBrokerError as exc:
                detail = ""
                try:
                    self._process.wait(timeout=1)
                except subprocess.TimeoutExpired:
                    pass
                if self._process.poll() is not None and self._process.stderr is not None:
                    detail = self._process.stderr.read(4096).decode(
                        "utf-8", errors="replace"
                    ).strip()
                raise KimiProviderBrokerError(
                    "broker worker exited before readiness "
                    f"(returncode={self._process.poll()}): {detail or 'no diagnostic'}"
                ) from exc
            for descriptor in descriptors:
                os.close(descriptor)
            if (
                set(ready) != {"ok", "operation", "pid"}
                or ready.get("ok") is not True
                or ready.get("operation") != "ready"
                or ready.get("pid") != self.pid
            ):
                raise KimiProviderBrokerError("broker worker did not attest readiness")
            self._control.settimeout(10.0)
            self._validate_live_identity()
            self._validate_evidence_files()
        except BaseException:
            child_control.close()
            self._stop_owned_process()
            self._control.close()
            self._closed = True
            raise

    def _validate_live_identity(self) -> None:
        if self._process is None or self._process.poll() is not None:
            raise KimiProviderBrokerError("broker worker is not running")
        if _process_start_time(self.pid) != self.start_time:
            raise KimiProviderBrokerError("broker PID identity drifted")
        try:
            executable = Path(f"/proc/{self.pid}/exe").resolve(strict=True)
        except OSError as exc:
            raise KimiProviderBrokerError("broker executable is not observable") from exc
        if (
            executable != self.process_executable_path
            or not hmac.compare_digest(
                _file_sha256(executable), self.process_executable_sha256
            )
        ):
            raise KimiProviderBrokerError("broker executable identity drifted")

    def _validate_evidence_files(self) -> None:
        for path in (
            self.attestation_path,
            self.audit_attestation_path,
            self.audit_log_path,
        ):
            if not path.is_file() or path.is_symlink() or stat.S_IMODE(path.stat().st_mode) != 0o600:
                raise KimiProviderBrokerError("broker evidence is absent or not private")
        if (
            not self.socket_path.exists()
            or self.socket_path.is_symlink()
            or not stat.S_ISSOCK(self.socket_path.stat().st_mode)
            or stat.S_IMODE(self.socket_path.stat().st_mode) != 0o600
        ):
            raise KimiProviderBrokerError("broker socket is absent or not private")
        audit = json.loads(self.audit_attestation_path.read_text(encoding="utf-8"))
        if (
            audit.get("run_id") != self.run_id
            or audit.get("case_id") != self.case_id
            or audit.get("trial_id") != self.trial_id
            or audit.get("pid") != self.pid
        ):
            raise KimiProviderBrokerError("broker audit identity drifted")

    def _rpc(
        self, document: Mapping[str, Any], *, expect_descriptor: bool = False
    ) -> tuple[Mapping[str, Any], int | None]:
        with self._rpc_lock:
            if self._closed:
                raise KimiProviderBrokerError("broker is closed")
            self._validate_live_identity()
            _send_packet(self._control, document)
            response, descriptors = _recv_packet(self._control)
        if response.get("ok") is not True:
            for descriptor in descriptors:
                os.close(descriptor)
            raise KimiProviderBrokerError(
                f"broker rejected {document.get('operation')}: {response.get('reason')}"
            )
        if expect_descriptor:
            if len(descriptors) != 1:
                for descriptor in descriptors:
                    os.close(descriptor)
                raise KimiProviderBrokerError("broker returned an invalid descriptor set")
            return response, descriptors[0]
        if descriptors:
            for descriptor in descriptors:
                os.close(descriptor)
            raise KimiProviderBrokerError("broker returned an unexpected descriptor")
        return response, None

    def issue_nonce_fd(
        self, *, run_id: str, stage_index: int, purpose: str
    ) -> BrokerNonceFD:
        if run_id != self.run_id:
            raise KimiProviderBrokerError("cross-run nonce issuance rejected")
        if (
            not isinstance(stage_index, int)
            or isinstance(stage_index, bool)
            or stage_index < -1
            or not isinstance(purpose, str)
            or _SAFE_ID_RE.fullmatch(purpose) is None
        ):
            raise KimiProviderBrokerError("nonce lease identity is malformed")
        response, descriptor = self._rpc(
            {
                "operation": "issue_nonce",
                "run_id": run_id,
                "case_id": self.case_id,
                "trial_id": self.trial_id,
                "stage_index": stage_index,
                "purpose": purpose,
            },
            expect_descriptor=True,
        )
        assert descriptor is not None
        lease_id = response.get("lease_id")
        try:
            if (
                not isinstance(lease_id, str)
                or _SAFE_ID_RE.fullmatch(lease_id) is None
                or "kimi" not in lease_id.casefold()
                or self.run_id not in lease_id
            ):
                raise KimiProviderBrokerError("broker returned an invalid lease identity")
            metadata = os.fstat(descriptor)
            seals = fcntl.fcntl(descriptor, fcntl.F_GET_SEALS)
            flags = fcntl.fcntl(descriptor, fcntl.F_GETFD)
            required = (
                fcntl.F_SEAL_SEAL
                | fcntl.F_SEAL_SHRINK
                | fcntl.F_SEAL_GROW
                | fcntl.F_SEAL_WRITE
            )
            if (
                not stat.S_ISREG(metadata.st_mode)
                or metadata.st_size != 32
                or seals & required != required
                or flags & fcntl.FD_CLOEXEC == 0
                or os.lseek(descriptor, 0, os.SEEK_CUR) != 0
                or "memfd:" not in os.readlink(f"/proc/self/fd/{descriptor}")
            ):
                raise KimiProviderBrokerError("broker returned an unsafe nonce descriptor")
        except BaseException:
            os.close(descriptor)
            raise
        # LinuxBubblewrapLauncher currently validates the concrete lease class
        # as well as its fields.  Import lazily so the standalone worker does
        # not import the launcher and a future integration can avoid a module
        # initialization cycle.
        from .isolated_launcher import BrokerNonceFD as LauncherBrokerNonceFD

        return LauncherBrokerNonceFD(fd=descriptor, lease_id=lease_id)

    def release_nonce(
        self,
        lease_id: str,
        *,
        run_id: str,
        stage_index: int,
        purpose: str,
    ) -> None:
        if run_id != self.run_id:
            raise KimiProviderBrokerError("cross-run nonce release rejected")
        self._rpc(
            {
                "operation": "release_nonce",
                "lease_id": lease_id,
                "run_id": run_id,
                "case_id": self.case_id,
                "trial_id": self.trial_id,
                "stage_index": stage_index,
                "purpose": purpose,
            }
        )

    @property
    def active_lease_count(self) -> int:
        response, _ = self._rpc(
            {
                "operation": "status",
                "run_id": self.run_id,
                "case_id": self.case_id,
                "trial_id": self.trial_id,
            }
        )
        count = response.get("active_lease_count")
        if not isinstance(count, int) or isinstance(count, bool) or count < 0:
            raise KimiProviderBrokerError("broker returned an invalid lease count")
        return count

    def configure_instruction_observer(
        self,
        *,
        run_id: str,
        stage_index: int,
        marker: bytes,
        expected_roles: Sequence[str] = ("system", "user", "user"),
    ) -> Path:
        """Arm a body-redacting observer before one stage starts.

        The marker is sent only over the private parent/worker control socket
        and retained in worker memory.  It is never written to the observer
        evidence file.
        """

        if run_id != self.run_id:
            raise KimiProviderBrokerError("cross-run observer configuration rejected")
        if (
            not isinstance(stage_index, int)
            or isinstance(stage_index, bool)
            or stage_index < 0
            or not isinstance(marker, bytes)
            or not 1 <= len(marker) <= _MAX_INSTRUCTION_MARKER
            or b"\0" in marker
        ):
            raise KimiProviderBrokerError("instruction observer marker is invalid")
        try:
            marker.decode("utf-8")
        except UnicodeDecodeError as exc:
            raise KimiProviderBrokerError(
                "instruction observer marker must be UTF-8"
            ) from exc
        roles = tuple(expected_roles)
        if (
            not roles
            or len(roles) > 64
            or any(
                not isinstance(role, str)
                or _SAFE_ID_RE.fullmatch(role) is None
                for role in roles
            )
        ):
            raise KimiProviderBrokerError("instruction observer roles are invalid")
        if stage_index in self._instruction_observers:
            raise KimiProviderBrokerError(
                "instruction observer is already configured for this stage"
            )
        marker_sha256 = hashlib.sha256(marker).hexdigest()
        response, _ = self._rpc(
            {
                "operation": "configure_instruction_observer",
                "run_id": self.run_id,
                "case_id": self.case_id,
                "trial_id": self.trial_id,
                "stage_index": stage_index,
                "marker_base64": base64.b64encode(marker).decode("ascii"),
                "marker_sha256": marker_sha256,
                "expected_roles": list(roles),
            }
        )
        raw_path = response.get("path")
        if not isinstance(raw_path, str):
            raise KimiProviderBrokerError("broker omitted observer path")
        path = Path(raw_path).absolute()
        try:
            path.relative_to(self.root)
        except ValueError as exc:
            raise KimiProviderBrokerError("observer path escapes broker root") from exc
        expected_name = (
            f"request-observer-kimi-{self.run_id}-stage-{stage_index:03d}.jsonl"
        )
        if (
            path.name != expected_name
            or path.is_symlink()
            or not path.is_file()
            or stat.S_IMODE(path.stat().st_mode) != 0o600
            or path.read_bytes()
        ):
            raise KimiProviderBrokerError("broker observer file is not a private empty file")
        self._instruction_observers[stage_index] = (path, marker_sha256, roles)
        return path

    def finalize_instruction_observer(
        self, *, run_id: str, stage_index: int
    ) -> InstructionRequestObservation:
        """Freeze and validate direct evidence for one stage request."""

        if run_id != self.run_id:
            raise KimiProviderBrokerError("cross-run observer finalization rejected")
        configured = self._instruction_observers.get(stage_index)
        if configured is None:
            raise KimiProviderBrokerError(
                "instruction observer was not configured for this stage"
            )
        path, marker_sha256, expected_roles = configured
        response, _ = self._rpc(
            {
                "operation": "finalize_instruction_observer",
                "run_id": self.run_id,
                "case_id": self.case_id,
                "trial_id": self.trial_id,
                "stage_index": stage_index,
            }
        )
        if path.is_symlink() or not path.is_file() or stat.S_IMODE(path.stat().st_mode) != 0o600:
            raise KimiProviderBrokerError("instruction observer path drifted")
        raw = path.read_bytes()
        digest = hashlib.sha256(raw).hexdigest()
        lines = raw.splitlines()
        if (
            response.get("path") != str(path)
            or response.get("sha256") != digest
            or response.get("line_count") != len(lines)
        ):
            raise KimiProviderBrokerError("instruction observer snapshot drifted")
        matches: list[tuple[int, Mapping[str, Any]]] = []
        for line_number, line in enumerate(lines, 1):
            try:
                record = json.loads(line)
            except json.JSONDecodeError as exc:
                raise KimiProviderBrokerError(
                    "instruction observer contains malformed JSON"
                ) from exc
            if not isinstance(record, Mapping) or (
                record.get("schema_name") != REQUEST_OBSERVATION_SCHEMA_NAME
                or record.get("schema_version") != REQUEST_OBSERVATION_SCHEMA_VERSION
                or record.get("harness_id") != "kimi"
                or record.get("run_id") != self.run_id
                or record.get("case_id") != self.case_id
                or record.get("trial_id") != self.trial_id
                or record.get("stage_index") != stage_index
                or record.get("sequence") != line_number
                or not isinstance(record.get("time"), str)
                or not isinstance(record.get("body_sha256"), str)
                or _SHA256_RE.fullmatch(str(record.get("body_sha256"))) is None
                or record.get("expected_substring_sha256") != marker_sha256
            ):
                raise KimiProviderBrokerError(
                    "instruction observer record identity/hash drifted"
                )
            if (
                record.get("expected_substring_present") is True
                and record.get("message_roles") == list(expected_roles)
            ):
                matches.append((line_number, record))
        if not matches:
            raise KimiProviderBrokerError(
                "no provider request directly contained the configured instruction marker"
            )
        line_number, record = matches[0]
        return InstructionRequestObservation(
            path=path,
            sha256=digest,
            line=line_number,
            line_count=len(lines),
            body_sha256=str(record["body_sha256"]),
            marker_sha256=marker_sha256,
            message_roles=expected_roles,
            observed_time=str(record["time"]),
        )

    def _stop_owned_process(self) -> None:
        process = self._process
        if process is None or process.poll() is not None:
            return
        try:
            if _process_start_time(process.pid) != getattr(self, "start_time", None):
                return
            process.terminate()
            process.wait(timeout=3)
        except (KimiProviderBrokerError, subprocess.TimeoutExpired):
            if process.poll() is None and _process_start_time(process.pid) == getattr(
                self, "start_time", None
            ):
                process.kill()
                process.wait(timeout=3)

    def close(self) -> None:
        if self._closed:
            return
        try:
            try:
                self._rpc(
                    {
                        "operation": "shutdown",
                        "run_id": self.run_id,
                        "case_id": self.case_id,
                        "trial_id": self.trial_id,
                    }
                )
            except (KimiProviderBrokerError, OSError):
                pass
            if self._process is not None:
                try:
                    self._process.wait(timeout=5)
                except subprocess.TimeoutExpired:
                    self._stop_owned_process()
        finally:
            self._closed = True
            self._control.close()
            if self._process is not None and self._process.stderr is not None:
                self._process.stderr.close()

    def __enter__(self) -> "RunScopedProviderBroker":
        return self

    def __exit__(self, *_: object) -> None:
        self.close()


