class KimiProviderBrokerError(RuntimeError):
    """The provider broker could not preserve its credential boundary."""


def _require_id(value: str, label: str) -> str:
    if not isinstance(value, str) or _SAFE_ID_RE.fullmatch(value) is None:
        raise KimiProviderBrokerError(
            f"{label} must be 1-160 safe ASCII characters"
        )
    return value


def _require_run_id(value: str) -> str:
    if not isinstance(value, str) or _RUN_ID_RE.fullmatch(value) is None:
        raise KimiProviderBrokerError(
            "run_id must be 1-80 safe ASCII characters"
        )
    return value


def broker_identity_digest(run_id: str, case_id: str, trial_id: str) -> str:
    """Return the collision-resistant short identity used by the socket root."""

    checked_run = _require_run_id(run_id)
    checked_case = _require_id(case_id, "case_id")
    checked_trial = _require_id(trial_id, "trial_id")
    return hashlib.sha256(
        f"{checked_run}\0{checked_case}\0{checked_trial}".encode("utf-8")
    ).hexdigest()[:SERVICE_IDENTITY_DIGEST_HEX_LENGTH]


def broker_root_name(run_id: str, case_id: str, trial_id: str) -> str:
    return f"{BROKER_ROOT_PREFIX}-{broker_identity_digest(run_id, case_id, trial_id)}"


def _canonical_sha256(document: Mapping[str, Any]) -> str:
    return hashlib.sha256(
        json.dumps(
            document,
            sort_keys=True,
            separators=(",", ":"),
            ensure_ascii=False,
        ).encode("utf-8")
    ).hexdigest()


def _file_sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _process_start_time(pid: int) -> str:
    try:
        raw = Path(f"/proc/{pid}/stat").read_text(encoding="utf-8")
    except OSError as exc:
        raise KimiProviderBrokerError("broker process is not observable") from exc
    closing = raw.rfind(")")
    fields = raw[closing + 1 :].split() if closing >= 0 else []
    if len(fields) < 20:
        raise KimiProviderBrokerError("broker process stat is malformed")
    return fields[19]


def _process_cmdline_sha256(pid: int) -> str:
    try:
        value = Path(f"/proc/{pid}/cmdline").read_bytes()
    except OSError as exc:
        raise KimiProviderBrokerError("broker cmdline is not observable") from exc
    if not value:
        raise KimiProviderBrokerError("broker cmdline is empty")
    return hashlib.sha256(value).hexdigest()


def _ack_proof(
    nonce: bytes | bytearray,
    *,
    run_id: str,
    stage_index: int,
    purpose: str,
    ok: bool,
) -> str:
    message = "\0".join(
        (
            HANDSHAKE_SCHEMA_NAME,
            run_id,
            str(stage_index),
            purpose,
            "ok" if ok else "rejected",
        )
    ).encode("utf-8")
    return hmac.new(bytes(nonce), message, hashlib.sha256).hexdigest()


def _wipe(value: bytearray) -> None:
    for index in range(len(value)):
        value[index] = 0


def _is_relative_to(path: Path, parent: Path) -> bool:
    try:
        path.relative_to(parent)
        return True
    except ValueError:
        return False


def _reject_symlink_chain(path: Path, *, stop: Path, label: str) -> None:
    candidate = path.absolute()
    boundary = stop.absolute()
    while True:
        if candidate.is_symlink():
            raise KimiProviderBrokerError(f"{label} has a symlink component")
        if candidate == boundary:
            return
        if candidate.parent == candidate or not _is_relative_to(candidate, boundary):
            raise KimiProviderBrokerError(f"{label} escapes ownership_root")
        candidate = candidate.parent


def _atomic_json(path: Path, document: Mapping[str, Any]) -> None:
    if path.exists() or path.is_symlink():
        raise KimiProviderBrokerError(f"refusing to replace broker evidence: {path}")
    descriptor, temporary_name = tempfile.mkstemp(
        dir=path.parent, prefix="tmp-kimi-provider-broker-"
    )
    temporary = Path(temporary_name)
    try:
        os.fchmod(descriptor, 0o600)
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            json.dump(document, handle, indent=2, sort_keys=True, ensure_ascii=False)
            handle.write("\n")
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
    finally:
        if temporary.exists():
            temporary.unlink()


@dataclass(frozen=True)
class UpstreamEndpoint:
    """A validated, non-proxy upstream destination."""

    scheme: str
    host: str
    port: int
    path_prefix: str
    tls_verified: bool

    @classmethod
    def parse(
        cls,
        value: str,
        *,
        allowed_https_hosts: Sequence[str] = (),
    ) -> "UpstreamEndpoint":
        if not isinstance(value, str) or not value or "\0" in value:
            raise KimiProviderBrokerError("upstream URL must be a non-empty string")
        parsed = urlsplit(value)
        if (
            parsed.scheme not in {"http", "https"}
            or parsed.hostname is None
            or parsed.username is not None
            or parsed.password is not None
            or parsed.query
            or parsed.fragment
        ):
            raise KimiProviderBrokerError("upstream URL shape is not allowed")
        try:
            port = parsed.port or (443 if parsed.scheme == "https" else 80)
        except ValueError as exc:
            raise KimiProviderBrokerError("upstream port is malformed") from exc
        if not 1 <= port <= 65535:
            raise KimiProviderBrokerError("upstream port is out of range")
        path_prefix = parsed.path.rstrip("/") or "/"
        if not path_prefix.startswith("/") or ".." in path_prefix.split("/"):
            raise KimiProviderBrokerError("upstream path prefix is unsafe")
        raw_host = parsed.hostname.rstrip(".").casefold()
        if parsed.scheme == "http":
            try:
                address = ipaddress.ip_address(raw_host)
            except ValueError as exc:
                raise KimiProviderBrokerError(
                    "plain HTTP upstream must use a loopback IP literal"
                ) from exc
            if not address.is_loopback:
                raise KimiProviderBrokerError(
                    "plain HTTP upstream must use a loopback IP literal"
                )
            host = address.compressed
            tls_verified = False
        else:
            try:
                ipaddress.ip_address(raw_host)
            except ValueError:
                pass
            else:
                raise KimiProviderBrokerError(
                    "production HTTPS upstream must use an allowlisted DNS host"
                )
            try:
                host = raw_host.encode("idna").decode("ascii")
            except UnicodeError as exc:
                raise KimiProviderBrokerError("HTTPS upstream host is invalid") from exc
            if _DNS_NAME_RE.fullmatch(host) is None:
                raise KimiProviderBrokerError("HTTPS upstream host is invalid")
            normalized_allowlist = {
                item.rstrip(".").casefold().encode("idna").decode("ascii")
                for item in allowed_https_hosts
                if isinstance(item, str) and item
            }
            if host not in normalized_allowlist:
                raise KimiProviderBrokerError(
                    "HTTPS upstream host lacks an exact constructor allowlist entry"
                )
            tls_verified = True
        return cls(
            scheme=parsed.scheme,
            host=host,
            port=port,
            path_prefix=path_prefix,
            tls_verified=tls_verified,
        )

    @property
    def authority(self) -> str:
        default = 443 if self.scheme == "https" else 80
        host = f"[{self.host}]" if ":" in self.host else self.host
        return host if self.port == default else f"{host}:{self.port}"


