"""Run-scoped credential broker for isolated Kimi Code benchmark stages.

The parent-side :class:`RunScopedProviderBroker` never accepts a credential as
text.  It starts exactly one child process for one ``run_id/case_id/trial_id``
and passes an already-open credential descriptor to that child.  The worker
reads and closes the descriptor before accepting clients.  Credentials are
never placed in argv, the environment, an attestation, or an evidence file.

Kimi reaches the worker through the private AF_UNIX socket protocol consumed by
``sandbox_entry.py``.  A nonce is generated by the worker and returned to the
launcher as a sealed memfd over a private control socket.  Each nonce permits
one authenticated broker connection; that connection may carry sequential
HTTP/1.1 requests.  A second connection with the same nonce is a replay and is
rejected.

Only two upstream shapes are accepted:

* loopback IP-literal HTTP, intended for credential-free local validation; or
* HTTPS to one exact, constructor-reviewed DNS host.

The worker injects ``Authorization: Bearer ...`` after removing every client
authorization/proxy header.  It does not implement a general forward proxy.
"""

